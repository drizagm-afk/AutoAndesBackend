-- The annex references these tables but omits their DDL.
-- This schema implements the fields and many-to-many relationship in section 3.1.
CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(30) NOT NULL UNIQUE,
  password VARCHAR2(100) NOT NULL,
  nombrecompleto VARCHAR2(120) NOT NULL,
  activo NUMBER(1) DEFAULT 1 NOT NULL
);
CREATE TABLE roles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(30) NOT NULL UNIQUE
);
CREATE TABLE usuario_roles (
  usuarioid NUMBER NOT NULL REFERENCES usuarios(id),
  rolid NUMBER NOT NULL REFERENCES roles(id),
  PRIMARY KEY (usuarioid, rolid)
);
